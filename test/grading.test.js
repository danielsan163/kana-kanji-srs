const S = window.SRS;
let fail = 0;
function t(id, prompt, ans, want) {
  const it = S.byId.get(id);
  const g = S.grade(it, prompt, ans);
  const ok = g.result === want;
  if (!ok) fail++;
  console.log(ok ? 'ok  ' : 'FAIL', id, prompt, JSON.stringify(ans), '→', g.result, g.message || '');
}
